//go:build windows && realwsl && !gowslmock

// Real-WSL end-to-end tests: against a live distro, verify the EA stamp
// actually projects root ownership inside WSL and that a sub-custodian cannot
// reach a sibling's sub-tree. These are the only tests exercising the
// production path end to end.

package securefiles_test

import (
	"context"
	"os"
	"os/exec"
	"path"
	"path/filepath"
	"strconv"
	"strings"
	"testing"
	"time"

	"github.com/canonical/ubuntu-pro-for-wsl/common/wsltestutils"
	"github.com/canonical/ubuntu-pro-for-wsl/windows-agent/internal/securefiles"
	"github.com/stretchr/testify/require"
)

func TestProjectionRootOwnedInDistro(t *testing.T) {
	distroName, _ := requireRealWsl2Instance(t)

	// Two public directories side by side, the same host path, the same
	// instance: one the custodian serves, one it never touched.

	// The sealed tree mirrors production: the custodian stamps the public
	// directory root itself, and the sub-tree roots below it.
	dir := t.TempDir()
	sealedPath := filepath.Join(dir, "public")
	c, err := securefiles.Open(sealedPath)
	require.NoError(t, err)
	defer c.Close()

	sealed, err := c.Subdir("sealed_dir")
	require.NoError(t, err)
	defer sealed.Close()

	err = sealed.WriteFile("client.key", []byte("secret_client_key"))
	require.NoError(t, err)

	// The unstamped tree is the pre-custodian layout, and what a process
	// writing behind the custodian's back still produces: a plain directory
	// with plain nodes, no extended attributes anywhere in the chain.
	unstampedPath := filepath.Join(dir, "unstamped-public")
	require.NoError(t, os.Mkdir(unstampedPath, 0755), "Setup: could not create the unstamped public directory")
	require.NoError(t, os.WriteFile(filepath.Join(unstampedPath, "planted.txt"), []byte("planted"), 0644),
		"Setup: could not plant the unstamped node")

	ctx, cancel := context.WithTimeout(context.Background(), 1*time.Minute)
	defer cancel()

	// The instance names these paths, not the test: the automount root is the
	// instance's to configure (wsl.conf), so its own wslpath is the only
	// honest translation of a host path. It is lexical — it translates the
	// name, it does not touch the node — so the parent is translated once and
	// the children are composed beneath it.
	dirWsl := wslPath(ctx, t, distroName, dir)
	sealedDirWsl := path.Join(dirWsl, "public", "sealed_dir")
	clientKeyWsl := path.Join(sealedDirWsl, "client.key")
	plantedWsl := path.Join(dirWsl, "unstamped-public", "planted.txt")

	// An unprivileged process inside the instance: uid 65534, no account
	// needed, no session started — the adversary the threat model names.
	// The mode bits alone cannot answer for it: a node projecting 0777
	// inside a sealed tree is still unreachable, its parent's traversal
	// refused first; only the operations the process attempts answer for
	// the whole chain being open.
	unpriv := "setpriv --reuid=65534 --regid=65534 --clear-groups"

	out, err := exec.CommandContext(ctx, "wsl.exe", "-d", distroName, "-u", "root", "--", "stat", "-c", "%u:%g:%a", sealedDirWsl).CombinedOutput() //nolint:gosec // Distro name is generated by the test and WSL paths are derived from t.TempDir().
	require.NoError(t, err, "stat sealed_dir output: %s", out)
	require.Equal(t, "0:0:700", strings.TrimSpace(string(out)))

	out, err = exec.CommandContext(ctx, "wsl.exe", "-d", distroName, "-u", "root", "--", "stat", "-c", "%u:%g:%a", clientKeyWsl).CombinedOutput() //nolint:gosec // Distro name is generated by the test and WSL paths are derived from t.TempDir().
	require.NoError(t, err, "stat client.key output: %s", out)
	require.Equal(t, "0:0:600", strings.TrimSpace(string(out)))

	// The stamped modes are the projection's promise. The unstamped node's
	// mode is the threat itself: whatever owns it, every unprivileged process
	// in the instance can read and overwrite it — which is the whole reason
	// the stamp exists (ADR 2.01). The owner is whatever the instance's
	// default user maps to, so only the mode is invariant: the projection
	// answers 0777, and a driver change that stops doing so is exactly what
	// this assertion exists to flag.
	out, err = exec.CommandContext(ctx, "wsl.exe", "-d", distroName, "-u", "root", "--", "stat", "-c", "%a", plantedWsl).CombinedOutput() //nolint:gosec // Distro name is generated by the test and WSL paths are derived from t.TempDir().
	require.NoError(t, err, "stat planted.txt output: %s", out)
	mode, err := strconv.ParseUint(strings.TrimSpace(string(out)), 8, 32)
	require.NoError(t, err, "the projected mode must be octal digits")
	require.NotZero(t, mode&0o002,
		"an unstamped node must project as world-writable (mode %#o); if this fails, the WSL projection changed and the threat ADR 2.01 closes changed shape", mode)

	// The sealed tree refuses the unprivileged process.
	out, err = exec.CommandContext(ctx, "wsl.exe", "-d", distroName, "-u", "root", "--", "sh", "-c", unpriv+" cat "+clientKeyWsl).CombinedOutput() //nolint:gosec // Distro name is generated by the test and WSL paths are derived from t.TempDir().
	require.Error(t, err, "Expected permission denied when unprivileged process reads key: output: %s", out)

	// The unstamped tree does not: the same process reads it,
	out, err = exec.CommandContext(ctx, "wsl.exe", "-d", distroName, "-u", "root", "--", "sh", "-c", unpriv+" cat "+plantedWsl).CombinedOutput() //nolint:gosec // Distro name is generated by the test and WSL paths are derived from t.TempDir().
	require.NoError(t, err, "an unstamped node must be world-readable: output: %s", out)
	require.Equal(t, "planted", strings.TrimSpace(string(out)))

	// and overwrites it: the exploit itself, against the very tree the
	// custodian exists to close.
	out, err = exec.CommandContext(ctx, "wsl.exe", "-d", distroName, "-u", "root", "--", "sh", "-c", unpriv+" sh -c 'echo tampered > "+plantedWsl+"'").CombinedOutput() //nolint:gosec // Distro name is generated by the test and WSL paths are derived from t.TempDir().
	require.NoError(t, err, "an unprivileged process must be able to overwrite an unstamped node — the exploit the stamp closes: output: %s", out)
}

// TestSubScopedCustodianCannotReachSibling proves the sub-scoping property the
// cloud-init writer relies on: a custodian scoped to one sub-tree cannot name,
// let alone write, a node in a sibling sub-tree, so per-distro data can never
// reach the certificates.
func TestSubScopedCustodianCannotReachSibling(t *testing.T) {
	t.Parallel()

	publicDir := t.TempDir()

	// Seed a sibling file that a sub-scoped custodian must not be able to touch.
	siblingPath := filepath.Join(publicDir, "certificates", "sibling.key")
	require.NoError(t, os.MkdirAll(filepath.Dir(siblingPath), 0700))
	require.NoError(t, os.WriteFile(siblingPath, []byte("sibling"), 0600))

	parent, err := securefiles.Open(publicDir)
	require.NoError(t, err)
	defer parent.Close()

	custodian, err := parent.Subdir(".cloud-init")
	require.NoError(t, err)
	defer custodian.Close()

	// Attempting to name a file so the path escapes the sub-tree must fail.
	err = custodian.WriteFile("../certificates/sibling", []byte("data"))
	require.ErrorIs(t, err, securefiles.ErrPathEscapes)

	// The sibling content must be untouched.
	got, err := os.ReadFile(siblingPath)
	require.NoError(t, err)
	require.Equal(t, "sibling", string(got))
}

func requireRealWsl2Instance(t *testing.T) (string, string) {
	t.Helper()

	rootFsPath := os.Getenv("UP4W_TEST_ROOTFS")
	require.NotEmpty(t, rootFsPath, "Setup: projection test requires real distro rootfs available (set UP4W_TEST_ROOTFS)")

	ctx, cancel := context.WithTimeout(context.Background(), 2*time.Minute)
	defer cancel()

	distroName := wsltestutils.RandomDistroName(t)
	guid := wsltestutils.PowershellInstallDistro(t, ctx, distroName, rootFsPath)

	return distroName, guid
}

// wslPath asks the distro instance to translate a Windows path: the automount
// root is the instance's to configure (wsl.conf), so its own wslpath is the
// only honest translation. wslpath is lexical — it maps the name without
// touching the node — so it answers for paths the test has not created yet.
func wslPath(ctx context.Context, t *testing.T, distroName, windowsPath string) string {
	t.Helper()

	// wsl.exe re-parses its command line and treats backslashes as escapes,
	// so a Windows path must travel with forward slashes; wslpath accepts
	// both and answers the same.
	slashPath := filepath.ToSlash(windowsPath)
	out, err := exec.CommandContext(ctx, "wsl.exe", "-d", distroName, "-u", "root", "--", "wslpath", "-a", slashPath).CombinedOutput() //nolint:gosec // Distro name is generated by the test; the path comes from t.TempDir().
	require.NoError(t, err, "wslpath %s output: %s", windowsPath, out)
	return strings.TrimSpace(string(out))
}
